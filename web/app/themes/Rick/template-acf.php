    <h2>Bereidingswijze</h2>
    <ul class="steps">
        <h3>1. Het Deeg Bereiden & Rijzen</h3>
        <li>Meng de bloem, de droge gist en het zout in een grote kom.</li>
        <li>Maak een kuiltje in het midden van het mengsel, roer de honing erdoor en giet het warme water erin.</li>
        <li>Meng dit en kneed dit tot een zacht, soepel deeg.</li>
        <li>Kneed ongeveer 7-10 minuten met een keukenmachine tot het deeg mooi elastisch is.</li>
        <li>Dek de kom vervolgens af met een vochtige doek of een douchemuts.</li>
        <li>Zet de kom ongeveer 1 uur op een warme plek zodat het deeg kan rijzen en in grootte kan verdubbelen.</li>

        <h3>2. Vorm Geven & Bakken</h3>
        <li>Trek een stukje van ongeveer 80 g van het deeg en maak er met je hands een mooi, egaal balletje van.</li>
        <li>Pak het deeg aan één kant vast en druk voorzichtig op de bovenkant van het balletje om het licht af te
            platten.</li>
        <li>Verwarm de oven voor op 200°C.</li>
        <li>Druk met een speciale stempel voor kaiserbroodjes in elk balletje om de bekende, klassieke windmolenvorm te
            krijgen.</li>
        <li>Leg de gevormde kaiserbroodjes op een met bakpapier beklede bakplaat.</li>
        <li>Schuif de bakplaat in de oven en bak de broodjes gedurende 15-20 minuten goudbruin en gaar.</li>
    </ul>

